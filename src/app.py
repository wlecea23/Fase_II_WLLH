@app.post("/predict")
def predict_transaction(
    transaction: Transaction
):

    try:

        values = list(
            transaction.dict().values()
        )

        result = predict(values)

        return result

    except Exception as e:

        raise HTTPException(
            status_code=500,
            detail=str(e)
        )